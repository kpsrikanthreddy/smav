-- 5. Offline Sync Jobs & Audit Logs (Enforces zero data loss and idempotency)
CREATE TABLE IF NOT EXISTS offline_sync_jobs (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    business_id VARCHAR(64) NOT NULL REFERENCES smav_businesses(id) ON DELETE CASCADE,
    branch_id VARCHAR(64) NOT NULL REFERENCES smav_branches(id) ON DELETE CASCADE,
    device_id VARCHAR(128) NOT NULL,
    idempotency_key VARCHAR(160) NOT NULL UNIQUE,
    entity_type VARCHAR(50) NOT NULL, -- 'salon_bill', 'restaurant_order', 'print_status'
    payload JSONB NOT NULL,
    status VARCHAR(50) DEFAULT 'queued', -- 'queued', 'processing', 'synced', 'conflict', 'failed'
    retry_count INT DEFAULT 0,
    last_error TEXT,
    created_at_local TIMESTAMPTZ NOT NULL,
    synced_at_server TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_offline_sync_jobs_status ON offline_sync_jobs(status);
CREATE INDEX IF NOT EXISTS idx_offline_sync_jobs_device ON offline_sync_jobs(device_id);

