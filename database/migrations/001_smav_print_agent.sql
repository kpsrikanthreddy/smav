-- 2. Registered Print Devices (Mobile terminals running SMAV Print Agent)
CREATE TABLE IF NOT EXISTS print_devices (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    device_id VARCHAR(128) NOT NULL UNIQUE, -- Android hardware ID / securely generated UUID
    business_id VARCHAR(64) NOT NULL REFERENCES smav_businesses(id) ON DELETE CASCADE,
    branch_id VARCHAR(64) NOT NULL REFERENCES smav_branches(id) ON DELETE CASCADE,
    device_name VARCHAR(255) NOT NULL, -- e.g. 'Samsung Galaxy Tab A8 - Salon Front Desk'
    model_info VARCHAR(255),
    app_version VARCHAR(50) DEFAULT '1.0.0',
    assigned_role VARCHAR(50) DEFAULT 'cashier', -- 'owner', 'manager', 'cashier', 'salon_receptionist'
    paired_at TIMESTAMPTZ DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ DEFAULT NOW(),
    last_sync_at TIMESTAMPTZ,
    is_active BOOLEAN DEFAULT TRUE,
    revoked_at TIMESTAMPTZ,
    revoked_reason TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_print_devices_business_branch ON print_devices(business_id, branch_id);
CREATE INDEX IF NOT EXISTS idx_print_devices_device_id ON print_devices(device_id);

